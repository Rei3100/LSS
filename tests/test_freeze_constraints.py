import pytest

from scripts import freeze_constraints


def test_constraints_skip_separately_indexed_torch_and_sort():
    frozen = "Torch==2.9.1+cu128\nnumpy==2.4.6\ntorchaudio==2.9.1+cu128\naudio-separator==0.48.0\n"
    assert freeze_constraints.constraint_lines(frozen) == ["audio-separator==0.48.0", "numpy==2.4.6"]


def test_a_path_or_url_install_stops_the_run():
    with pytest.raises(ValueError):
        freeze_constraints.constraint_lines("numpy==2.4.6\nlocalpkg @ file:///somewhere/localpkg\n")


def test_rendered_file_starts_with_the_header():
    text = freeze_constraints.render("numpy==2.4.6\n")
    assert text.startswith("# Generated by scripts/freeze_constraints.py")
    assert text.endswith("numpy==2.4.6\n")
