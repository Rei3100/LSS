import pytest

from scripts import freeze_constraints


def test_constraints_skip_separately_indexed_torch_and_sort():
    frozen = "Torch==2.9.1+cu128\nnumpy==2.4.6\ntorchaudio==2.9.1+cu128\naudio-separator==0.48.0\n"
    assert freeze_constraints.constraint_lines(frozen) == ["audio-separator==0.48.0", "numpy==2.4.6"]


def test_a_path_or_url_install_stops_the_run():
    with pytest.raises(ValueError):
        freeze_constraints.constraint_lines("numpy==2.4.6\nlocalpkg @ file:///somewhere/localpkg\n")


def test_rendered_file_starts_with_the_header():
    text = freeze_constraints.render("numpy==2.4.6\n")
    assert text.startswith("# Generated by scripts/freeze_constraints.py")
    assert text.endswith("numpy==2.4.6\n")


def test_build_requirements_stay_and_pip_is_left_to_the_runner():
    frozen = "pip==25.3\nsetuptools==84.2.1\nwheel==0.45.1\npyinstaller==6.22.3\n"
    assert freeze_constraints.constraint_lines(frozen) == ["pyinstaller==6.22.3", "setuptools==84.2.1", "wheel==0.45.1"]


def test_the_generator_asks_pip_for_every_package(monkeypatch, tmp_path):
    calls = []
    class Done:
        stdout = "setuptools==84.2.1\n"
    monkeypatch.setattr(freeze_constraints.subprocess, "run", lambda args, **k: calls.append(args) or Done())
    monkeypatch.setattr(freeze_constraints, "TARGET", tmp_path / "constraints.txt")
    assert freeze_constraints.main([]) == 0
    assert "--all" in calls[0]
    assert "setuptools==84.2.1" in (tmp_path / "constraints.txt").read_text(encoding="utf-8")
