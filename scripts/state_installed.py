"""Regenerate the "Installed Product" block of docs/current/STATE.md from .state/releases/current-product.json.

    python scripts/state_installed.py           # rewrite the marked block in place
    python scripts/state_installed.py --check   # exit 1 when the block is out of date (read-only)

The block sits between <!-- installed:begin --> and <!-- installed:end -->. Everything else in STATE.md is
hand-written. Standard library only; the file's existing line endings are preserved (bytes in, bytes out).
"""
from __future__ import annotations

import json
import os
import subprocess
import sys
from pathlib import Path

try:
    from scripts.dev_state import dev_state_root
except ModuleNotFoundError:  # Direct execution outside the checkout root.
    from dev_state import dev_state_root


ROOT = Path(__file__).resolve().parents[1]
BEGIN, END = "<!-- installed:begin -->", "<!-- installed:end -->"


def _git_ok(*args: str) -> bool:
    try:
        return subprocess.run(["git", "-C", str(ROOT), *args], capture_output=True, timeout=30,
                              creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0)).returncode == 0
    except (OSError, subprocess.SubprocessError):
        return False


def _release_file() -> Path:
    """Use configured development state, retaining legacy checkout discovery."""
    here = dev_state_root(ROOT) / "releases" / "current-product.json"
    if "LSS_DEV_STATE" in os.environ or here.is_file():
        return here
    try:
        common = subprocess.run(["git", "-C", str(ROOT), "rev-parse", "--git-common-dir"], capture_output=True,
                                text=True, timeout=30).stdout.strip()
        alt = dev_state_root((ROOT / common).resolve().parent) / "releases" / "current-product.json"
        if alt.is_file():
            return alt
    except (OSError, subprocess.SubprocessError):
        pass
    return here


def render(rec: dict) -> str:
    sha = str(rec.get("candidate_code_commit", ""))
    exe = str(rec.get("exe_sha256", ""))
    rb = rec.get("rollback") or {}
    ev = rec.get("evidence") or {}
    in_main = _git_ok("merge-base", "--is-ancestor", sha, "main") if sha else False
    date = str(rec.get("completed_at", ""))[:10]
    residual = rec.get("residual_limitations") or []
    lines = [
        BEGIN,
        "<!-- generated by scripts/state_installed.py from .state/releases/current-product.json; do not edit by hand -->",
        f"- Release `{rec.get('release_id')}` ({rec.get('release_branch')}), **{rec.get('outcome')}** {date}; "
        f"code `{sha[:7]}` ({'merged into `main`' if in_main else '**not yet in `main`**'}); "
        f"`{rec.get('deployed_executable')}` SHA-256 `{exe[:12]}…`.",
        f"- Rollback target `{rb.get('target_release_id')}` (EXE `{str(rb.get('known_good_exe_sha256', ''))[:12]}…`); "
        f"stop LSS first, then run `{rb.get('command')}`.",
        f"- Verdict: `{ev.get('independent_verifier', 'see record')}`.",
        f"- Declared residuals: {len(residual)} in the record (`residual_limitations`); read them there before judging a symptom.",
        "- Full record: `.state/releases/current-product.json`; Evidence roots in `docs/validation/INDEX.md`.",
        END,
    ]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    check = "--check" in argv
    rf = _release_file()
    if not rf.is_file():
        print("no .state/releases/current-product.json; nothing to render")
        return 0
    rec = json.loads(rf.read_text(encoding="utf-8"))
    target = ROOT / "docs" / "current" / "STATE.md"
    raw = target.read_bytes()
    text = raw.decode("utf-8")
    crlf = "\r\n" in text
    text = text.replace("\r\n", "\n")
    a, b = text.find(BEGIN), text.find(END)
    if a < 0 or b < a:
        print("STATE.md has no installed block markers", file=sys.stderr)
        return 1
    new = text[:a] + render(rec) + text[b + len(END):]
    if new == text:
        return 0
    if check:
        print("STATE.md Installed Product block is out of date: run python scripts/state_installed.py")
        return 1
    out = new.replace("\n", "\r\n") if crlf else new
    target.write_bytes(out.encode("utf-8"))
    print("STATE.md Installed Product block updated")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
