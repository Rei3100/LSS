"""Write constraints.txt from the development venv, so the hosted test job installs the versions developed against.

`requirements*.txt` name what is needed; `constraints.txt` fixes the version of everything installed, including
setuptools and wheel (`pip freeze --all`; PyInstaller requires setuptools). torch, torchaudio and torchvision are left
out: their builds come from a separate index (CUDA locally, CPU on the hosted runner) at the versions
`setup-venv.ps1` and the workflow pin. pip itself is left to the runner. Only plain `name==version` lines are
written; a package installed from a path or URL stops the run, because the file is published.

    .venv\\Scripts\\python scripts/freeze_constraints.py          # rewrite constraints.txt
    .venv\\Scripts\\python scripts/freeze_constraints.py --check  # exit 1 when the venv and the file differ
"""
from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "constraints.txt"
SEPARATE_INDEX = {"torch", "torchaudio", "torchvision"}
# pip installs everything else and is left to the runner; setuptools and wheel are build requirements and stay.
NOT_CONSTRAINED = SEPARATE_INDEX | {"pip"}
HEADER = ("# Generated by scripts/freeze_constraints.py from the development venv; do not edit by hand.\n"
          "# torch, torchaudio and torchvision are pinned where they are installed (setup-venv.ps1, ci.yml).\n")
PIN = re.compile(r"([A-Za-z0-9][A-Za-z0-9._-]*)==([A-Za-z0-9.!+_-]+)")


def constraint_lines(freeze_output: str) -> list[str]:
    lines = []
    for raw in freeze_output.splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        match = PIN.fullmatch(line)
        if not match:
            raise ValueError("Only name==version lines can be published; reinstall that package from an index")
        if match[1].lower().replace("_", "-") in NOT_CONSTRAINED:
            continue
        lines.append(line)
    return sorted(lines, key=str.lower)


def render(freeze_output: str) -> str:
    return HEADER + "".join(line + "\n" for line in constraint_lines(freeze_output))


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    frozen = subprocess.run([sys.executable, "-m", "pip", "freeze", "--all", "--exclude-editable"],
                            capture_output=True, text=True, check=True).stdout
    text = render(frozen)
    if args.check:
        current = TARGET.read_text(encoding="utf-8") if TARGET.is_file() else ""
        print("constraints.txt matches the venv" if current == text else "constraints.txt differs from the venv")
        return int(current != text)
    TARGET.write_text(text, encoding="utf-8", newline="\n")
    print(f"constraints.txt: {text.count(chr(10)) - 2} packages")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
