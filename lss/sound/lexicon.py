@dataclass(frozen=True)
class Concept:
    id: str
    label: str
    family: str
    prompt: str
    words: tuple[str, ...]
    audioset: tuple[str, ...] = ()
    parent: str = ""            # "auto": 音源ごとに、その音が最も聞こえる親を選ぶ

    @property
    def base_id(self) -> str:
        """修飾した音（``rain~distant``）の、元の語彙の音の識別。経路の選び方はこれで決める。"""
        return self.id.split("~", 1)[0]


def _c(id, label, family, prompt, words, audioset=(), parent=""):
    return Concept(id, label, family, prompt, tuple(words), tuple(audioset), parent)


