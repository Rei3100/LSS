def normalize(text: str) -> str:
    """照合用の正規形。全角半角・大小文字・空白の違いを消す。"""
    value = unicodedata.normalize("NFKC", text).casefold()
    return " ".join(value.split())


def _index() -> dict[str, Concept]:
    index: dict[str, Concept] = {}
    for concept in CONCEPTS:
        if concept.family not in FAMILIES:
            raise ValueError(f"未知の系統です: {concept.id}")
        for word in concept.words + (concept.label,):
            key = normalize(word)
            if key in index and index[key].id != concept.id:
                raise ValueError(f"語が2つの対象を指しています: {word} ({index[key].id}, {concept.id})")
            index[key] = concept
    return index


WORDS: dict[str, Concept] = _index()


def lookup(text: str) -> Concept | None:
    """語に完全一致する対象。無ければNone（推測で別の音へ置き換えない）。"""
    return WORDS.get(normalize(text))
