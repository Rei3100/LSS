"""欲しい音の語彙: 利用者の言葉（日本語・英語）と、LSSが扱う意味的な対象（concept）の対応。

conceptは「何の音か」であって、どのmodelのどのstemかではない。経路（どの分離器を、どの親の音に
対して使うか）は `lss.sound.plan` が音源の性質と合わせて決める。ここが持つのは:

- ``family``: 経路を決める意味の系統。
    ``speech``（台詞）/ ``lead_vocals``（リードボーカルだけ。コーラス・ハーモニーを含まない）/
    ``backing_vocals``（リード以外の歌声: コーラスとハーモニー）/ ``singing``（歌声全部）/
    ``music``（音楽全体）/ ``instrumental``（伴奏）/
    ``effects``（効果音全体）/ ``speech_part``（台詞の中の特定の声）/ ``singing_part``（歌の中の特定の声）/
    ``music_part``（音楽の中の楽器・編成）/ ``sound``（効果音・環境音の中の特定の音）
- ``prompt``: 言葉で分離するmodelへ渡す英語の名詞句（小文字・ASCII）。
- ``audioset``: 出力にその音があるかを確かめるAudioSetのクラス（無いconceptは音量だけで確かめる）。
- ``label``: 成果物のファイル名・表示に使う日本語。
- ``parent``: ``"auto"`` は、番組の台詞・音楽・効果音のどこにも鳴り得る音（口笛・鐘・拍手・オルゴール等）。
  固定の親を決めず、音源ごとにその音が最も聞こえる親を測って選ぶ（`lss.sound.plan`）。

語彙に無い日本語は推測で別の音へ置き換えない（`lss.sound.intent`）。英語の名詞句はそのまま
``sound`` として言葉で分離する。

``MODIFIERS`` は「子どもの笑い声」「遠くの雷」「怪獣の足音」のように、語彙の音を絞る日本語の修飾語と、その
英語。修飾した音は、元の音と同じ経路・同じ確かめ方で、言葉だけを「child laughter」のように絞る。
"""
